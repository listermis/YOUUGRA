const LEVEL_XP    = 350; // сколько XP нужно на 1-й уровень (1 → 2)
const LEVEL_STEP  = 60;  // на сколько растёт требование с каждым следующим уровнем

// Сколько XP нужно чтобы пройти уровень lvl (lvl → lvl+1), при базе base и приросте step
function levelReqOf(lvl, base, step) {
  return base + lvl * step;
}

// Уровень и прогресс внутри текущего уровня по суммарному XP: полоса всегда
// начинается с нуля на новом уровне, а порог следующего уровня растёт
function computeProgress(totalXp, base, step) {
  let level = 0;
  let rest  = totalXp;
  while (rest >= levelReqOf(level, base, step)) {
    rest -= levelReqOf(level, base, step);
    level++;
  }
  return { level, xpIntoLevel: rest, xpForLevel: levelReqOf(level, base, step) };
}

function levelReq(lvl) {
  return levelReqOf(lvl, LEVEL_XP, LEVEL_STEP);
}

function computeLevelProgress(totalXp) {
  return computeProgress(totalXp, LEVEL_XP, LEVEL_STEP);
}

// Характеристики и обычные навыки (Спорт/Психология/Заработок) — те же растущие уровни
const STAT_LVL_BASE = 100;
const STAT_LVL_STEP = 40;
function computeStatLevelProgress(xp) {
  return computeProgress(xp, STAT_LVL_BASE, STAT_LVL_STEP);
}

// Стиль — уровень считается вещами (не XP): 4 вещи на уровень, на новом уровне снова 4 пустых окна
const STYLE_ITEMS_PER_LEVEL = 4;
function computeStyleLevelProgress(items) {
  return {
    level:        Math.floor(items / STYLE_ITEMS_PER_LEVEL),
    itemsIntoLvl: items % STYLE_ITEMS_PER_LEVEL,
  };
}

