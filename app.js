function uid() {
  return Date.now().toString(36) + Math.random().toString(36).slice(2, 6);
}

function generateSchedule(state, ds) {
  const quests = [];
  const dow = dayOfWeek(ds);

  DAILY_QUESTS.forEach(q => quests.push({ ...q, uid: uid(), done: false }));

  if (WEEKLY_QUESTS[dow]) {
    quests.push({ ...WEEKLY_QUESTS[dow], uid: uid(), done: false });
  }

  if (isLastDayOfMonth(ds)) {
    quests.push({
      uid: uid(), id: 'boss',
      name: '⚔️ БОСС-ФАЙТ',
      detail: '40 берпи + 40 отжиманий + 40 пресса — победил = уровень вверх',
      xp: 15, skill: 'body', type: 'boss', done: false,
    });
  }

  return quests;
}

function ensureDay(state, ds) {
  if (!state.days[ds]) {
    state.days[ds] = { quests: generateSchedule(state, ds), earnedXp: 0, relapses: {}, tracked: {}, cigCount: 0 };
    saveState(state);
  }
  if (!state.days[ds].relapses) state.days[ds].relapses = {};
  if (!state.days[ds].tracked)  state.days[ds].tracked  = {};
  if (state.days[ds].cigCount === undefined) state.days[ds].cigCount = 0;
}

// Нарушение — снимает XP за день
function triggerDemerit(state, key, ds) {
  const debuff = state.character.debuffs[key];
  if (!debuff) return;
  const day = state.days[ds];
  if (!day) return;
  if (!day.relapses) day.relapses = {};
  day.relapses[key] = (day.relapses[key] || 0) + 1;
  recalc(state, ds);
  saveState(state);
}

// Отмена нарушения
function undoDemerit(state, key, ds) {
  const day = state.days[ds];
  if (!day?.relapses) return;
  if ((day.relapses[key] || 0) <= 0) return;
  day.relapses[key]--;
  recalc(state, ds);
  saveState(state);
}

// Явная отметка дня: "чисто" или "было" — без этого день не влияет на Волю,
// чтобы бездействие/неоткрытие приложения не засчитывалось как выдержка
function markDayTracked(state, key, ds, clean) {
  const day = state.days[ds];
  if (!day) return;
  if (!day.tracked) day.tracked = {};
  day.tracked[key] = clean;
  recalc(state, ds);
  saveState(state);
}

// Счётчик сигарет за день — при изменении сбрасываем отметку "день закрыт",
// чтобы пользователь заново подтвердил лимит после нового изменения
function adjustCigCount(state, ds, delta) {
  const day = state.days[ds];
  if (!day) return;
  day.cigCount = Math.max(0, (day.cigCount || 0) + delta);
  if (day.tracked && day.tracked.cigs !== undefined) delete day.tracked.cigs;
  recalc(state, ds);
  saveState(state);
}

