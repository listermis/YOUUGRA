function saveBossResult(count, xp) {
  const state    = _boss.mainState;
  const ds       = todayStr();
  const questUid = uid();
  const tl       = BOSS_TEMPO_LABELS[_boss.tempo] || _boss.tempo;
  const dl       = bossDurationLabel(_boss.durationMs);
  ensureDay(state, ds);
  state.days[ds].quests.push({
    uid: questUid, id: 'boss_' + Date.now(),
    name:   `Отжимания с боссом — ${count} повт.`,
    detail: `${tl} · ${dl}`,
    xp, skill: 'body', type: 'custom', done: true,
  });
  recalc(state, ds);
  saveState(state);
  renderAll(state, ds);
  return questUid;
}

function removeBossResult(questUid) {
  const state = _boss.mainState;
  const ds    = todayStr();
  const day   = state.days[ds];
  if (!day) return;
  day.quests = day.quests.filter(q => q.uid !== questUid);
  recalc(state, ds);
  saveState(state);
  renderAll(state, ds);
}

const BOSS_TEMPO_LABELS = { slow: 'МЕДЛ', mid: 'СР', fast: 'БЫСТР' };

function bossDurationLabel(ms) {
  if (!ms) return 'без лимита';
  const opt = BOSS_DURATION_OPTIONS.find(o => o.ms === ms);
  return opt ? opt.label : `${Math.round(ms / 1000)} сек`;
}

function deleteBossEntry(state, ds, questUid) {
  const day = state.days[ds];
  if (!day) return;
  day.quests = day.quests.filter(q => q.uid !== questUid);
  recalc(state, ds);
  saveState(state);
  renderAll(state, todayStr());
}

function renderBossHistory(state) {
  const listEl = $('bossHistoryList');
  if (!listEl) return;

  const entries = [];
  Object.keys(state.days).sort().reverse().forEach(ds => {
    state.days[ds].quests
      .filter(q => q.id && q.id.startsWith('boss_'))
      .forEach(q => entries.push({ ds, uid: q.uid, name: q.name, xp: q.xp, detail: q.detail }));
  });

  if (!entries.length) {
    listEl.innerHTML = '<div class="boss-history-empty">Нет записей</div>';
    return;
  }

  listEl.innerHTML = entries.map(e => {
    const d       = new Date(e.ds + 'T12:00:00').toLocaleDateString('ru-RU', { day: 'numeric', month: 'short' });
    const oldGeneric = !e.detail || e.detail === 'Битва с боссом';
    const detailTag  = oldGeneric ? '' : `<span class="boss-history-tag">${e.detail}</span>`;
    return `<div class="boss-history-item">
      <div class="boss-history-info">
        <span class="boss-history-name">${e.name}</span>
        <div class="boss-history-meta">${detailTag}<span class="boss-history-date">${d}</span></div>
      </div>
      <div class="boss-history-right">
        <span class="boss-history-xp">+${e.xp} XP</span>
        <button class="boss-history-del" data-uid="${e.uid}" data-ds="${e.ds}">✕</button>
      </div>
    </div>`;
  }).join('');

  listEl.querySelectorAll('.boss-history-del').forEach(btn => {
    btn.addEventListener('click', () => {
      deleteBossEntry(state, btn.dataset.ds, btn.dataset.uid);
      renderBossHistory(state);
    });
  });
}

function updateDurTimer() {
  const total   = Math.round(_boss.durationMs / 1000);
  const left    = _boss.durSecondsLeft || 0;
  const elapsed = total - left;
  const pct     = total > 0 ? (elapsed / total * 100) : 0;

  const fmt = s => `${String(Math.floor(s/60)).padStart(2,'0')}:${String(s%60).padStart(2,'0')}`;

  const elEl  = $('bossElapsedNum');
  const remEl = $('bossRemainingNum');
  const fill  = $('bossTimerFill');

  if (elEl)  elEl.textContent  = fmt(elapsed);
  if (remEl) {
    remEl.textContent = fmt(left);
    remEl.classList.toggle('danger', left <= 10);
  }
  if (fill)  fill.style.width  = pct + '%';
}

