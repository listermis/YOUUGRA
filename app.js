function getStyleItems(state) {
  const items = [];
  Object.entries(state.days).forEach(([ds, day]) => {
    day.quests.forEach(q => {
      if (q.skill === 'style' && q.done) items.push({ ds, uid: q.uid, name: q.name, xp: q.xp });
    });
  });
  return items.sort((a, b) => a.ds.localeCompare(b.ds));
}

