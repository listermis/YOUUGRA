// Ключи, для которых нужна явная ежедневная отметка "чисто"/"было" (влияет на Волю)
const TRACKABLE_KEYS = ['porn', 'reels'];

function renderDayDemerits(state, ds, containerId = 'dayDemerits') {
  const debuffs   = state.character.debuffs;
  const day       = state.days[ds];
  const relapses  = (day && day.relapses) ? day.relapses : {};
  const tracked   = (day && day.tracked)  ? day.tracked  : {};
  const cigCount  = day ? (day.cigCount || 0) : 0;
  const cigMarked = tracked.cigs; // true/false/undefined
  const container = $(containerId);
  if (!container) return;

  container.innerHTML = `
    <div class="quest-section-label">НАРУШЕНИЯ ДНЯ</div>
    ${Object.entries(debuffs).filter(([key]) => key !== 'cigs').map(([key, d]) => {
      const cnt        = relapses[key] || 0;
      const pen        = (d.xpCost || 0) * cnt;
      const active     = cnt > 0;
      const trackable  = TRACKABLE_KEYS.includes(key);
      const markedClean = tracked[key] === true;
      return `<div class="demerit-item ${active ? 'demerit-active' : ''}">
        <div class="demerit-body">
          <span class="demerit-name">${d.name}</span>
          <span class="demerit-cost">${d.detail}</span>
          ${trackable && markedClean ? `<span class="demerit-clean-tag">✓ отмечено: чисто</span>` : ''}
        </div>
        <div class="demerit-right">
          ${active ? `<span class="demerit-count">×${cnt} = −${pen} XP</span>` : ''}
          ${active ? `<button class="demerit-undo-btn" data-key="${key}">−</button>` : ''}
          ${trackable && !active ? `<button class="demerit-clean-btn ${markedClean ? 'is-marked' : ''}" data-key="${key}">${markedClean ? 'чисто ✓' : 'не было'}</button>` : ''}
          <button class="demerit-btn" data-key="${key}">было</button>
        </div>
      </div>`;
    }).join('')}
    <div class="demerit-item ${cigCount >= 4 ? 'demerit-active' : ''}">
      <div class="demerit-body">
        <span class="demerit-name">Сигареты</span>
        <span class="demerit-cost">лимит: меньше 4 в день</span>
        ${cigMarked === true  ? `<span class="demerit-clean-tag">✓ отмечено: ${cigCount} шт., в лимите</span>` : ''}
        ${cigMarked === false ? `<span class="demerit-cost" style="color:var(--red-text)">отмечено: перебор (${cigCount} шт.)</span>` : ''}
      </div>
      <div class="demerit-right">
        <span class="demerit-count">${cigCount} шт.</span>
        <button class="demerit-undo-btn cig-minus-btn" ${cigCount <= 0 ? 'disabled' : ''}>−</button>
        <button class="demerit-undo-btn cig-plus-btn">+</button>
        <button class="demerit-clean-btn cig-finish-btn ${cigMarked !== undefined ? 'is-marked' : ''}">${cigMarked !== undefined ? 'день отмечен ✓' : 'отметить день'}</button>
      </div>
    </div>
  `;

  // На главной странице (сегодняшний день) обновляем виджеты на месте.
  // В модале календаря (прошлый/чужой день) перерисовываем весь day-detail
  // и фоном обновляем главный дашборд — там свои #todayXp/#todayPenalty и т.д.,
  // которые нельзя перезаписывать данными чужого дня.
  const isCalendarCtx = containerId !== 'dayDemerits';
  const refresh = () => {
    if (isCalendarCtx) {
      showDayDetail(ds);
      renderAll(state, todayStr());
    } else {
      renderDayDemerits(state, ds, containerId);
      renderScheduleFooter(state, ds);
      renderHeader(state);
      renderCharacteristics(state);
    }
  };

  container.querySelectorAll('.demerit-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const key = btn.dataset.key;
      triggerDemerit(state, key, ds);
      if (TRACKABLE_KEYS.includes(key)) markDayTracked(state, key, ds, false);
      refresh();
    });
  });

  container.querySelectorAll('.demerit-undo-btn:not(.cig-minus-btn):not(.cig-plus-btn)').forEach(btn => {
    btn.addEventListener('click', () => {
      undoDemerit(state, btn.dataset.key, ds);
      refresh();
    });
  });

  container.querySelectorAll('.demerit-clean-btn:not(.cig-finish-btn)').forEach(btn => {
    btn.addEventListener('click', () => {
      markDayTracked(state, btn.dataset.key, ds, true);
      refresh();
    });
  });

  const cigPlusBtn  = container.querySelector('.cig-plus-btn');
  const cigMinusBtn = container.querySelector('.cig-minus-btn');
  const cigFinishBtn = container.querySelector('.cig-finish-btn');
  if (cigPlusBtn) cigPlusBtn.addEventListener('click', () => {
    adjustCigCount(state, ds, 1);
    refresh();
  });
  if (cigMinusBtn) cigMinusBtn.addEventListener('click', () => {
    adjustCigCount(state, ds, -1);
    refresh();
  });
  if (cigFinishBtn) cigFinishBtn.addEventListener('click', () => {
    const d = state.days[ds];
    const cnt = d ? (d.cigCount || 0) : 0;
    markDayTracked(state, 'cigs', ds, cnt < 4);
    refresh();
  });
}

