function checkStreak(state) {
  const t   = todayStr();
  const ysd = yesterdayStr();
  const last = state.meta.lastCompletedDate;

  if (!last) return;

  if (last < ysd) {
    state.meta.streak = 0;
    saveState(state);
  }
}

function updateStreakOnComplete(state) {
  const t   = todayStr();
  const ysd = yesterdayStr();
  const last = state.meta.lastCompletedDate;

  if (state.meta.streakUpdatedDate === t) return; // уже обновляли сегодня

  if (last === ysd) {
    state.meta.streak += 1;
  } else if (last !== t) {
    state.meta.streak = 1;
  }

  state.meta.streakUpdatedDate = t;
  state.meta.lastCompletedDate = t;
}

