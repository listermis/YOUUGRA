function horizonsAvailable(state) {
  const viewed = state.meta.horizonsViewed || [];
  return HORIZONS_POOL.filter(i => !viewed.includes(i.id));
}

function ensureTodayHorizons(state) {
  const t = todayStr();
  if (state.meta.horizonsTodayItem && state.meta.horizonsTodayItem.date === t) return;
  const pool = horizonsAvailable(state);
  if (!pool.length) { state.meta.horizonsTodayItem = null; saveState(state); return; }
  const item = pool[Math.floor(Math.random() * pool.length)];
  state.meta.horizonsTodayItem = { date: t, id: item.id };
  saveState(state);
}

function switchHorizonsItem(state) {
  const t = todayStr();
  const curId  = state.meta.horizonsTodayItem?.id;
  const viewed = state.meta.horizonsViewed || [];
  const pool   = HORIZONS_POOL.filter(i => !viewed.includes(i.id) && i.id !== curId);
  if (!pool.length) return;
  const item = pool[Math.floor(Math.random() * pool.length)];
  state.meta.horizonsTodayItem = { date: t, id: item.id };
  saveState(state);
}

function markHorizonsViewed(state, itemId) {
  if (!state.meta.horizonsViewed) state.meta.horizonsViewed = [];
  if (!state.meta.horizonsViewed.includes(itemId)) state.meta.horizonsViewed.push(itemId);
  const item = HORIZONS_POOL.find(i => i.id === itemId);
  const ds   = todayStr();
  ensureDay(state, ds);
  state.days[ds].quests.push({
    uid: uid(), id: 'horizons_' + itemId,
    name: item.title, detail: item.cat,
    xp: 3, skill: 'horizons', type: 'custom', done: true,
  });
  recalc(state, ds);
  state.meta.horizonsTodayItem = null;
  saveState(state);
}

function renderHorizonsBlock(state) {
  const container = $('horizonsBlock');
  if (!container) return;

  const pool = horizonsAvailable(state);
  const viewed = (state.meta.horizonsViewed || []).length;

  if (!pool.length) {
    container.innerHTML = `<div class="hd-done">✦ Ты изучил всё. Скоро добавим новое.</div>`;
    return;
  }

  const todayItem = state.meta.horizonsTodayItem;
  if (!todayItem || todayItem.date !== todayStr()) {
    container.innerHTML = '';
    return;
  }

  const item = HORIZONS_POOL.find(i => i.id === todayItem.id);
  if (!item) { container.innerHTML = ''; return; }

  const canSwitch = pool.length > 1;

  container.innerHTML = `
    <div class="hd-card">
      <div class="hd-cat">${item.cat}</div>
      <div class="hd-title">${item.title}</div>
      <div class="hd-progress">${viewed} / 200 изучено</div>
      <div class="hd-btns">
        <button class="btn-primary hd-btn-mark" id="btnHdMark">ОТМЕТИТЬ КАК ПРОСМОТРЕННОЕ</button>
        <button class="btn-ghost hd-btn-next" id="btnHdNext" ${canSwitch ? '' : 'disabled'}>ДРУГОЕ</button>
      </div>
    </div>`;

  $('btnHdMark').addEventListener('click', () => {
    markHorizonsViewed(state, item.id);
    ensureTodayHorizons(state);
    renderAll(state, todayStr());
    renderHorizonsBlock(state);
  });

  if (canSwitch) {
    $('btnHdNext').addEventListener('click', () => {
      switchHorizonsItem(state);
      renderHorizonsBlock(state);
    });
  }
}

