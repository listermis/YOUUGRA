function isActionAvailable(state, item) {
  const last = state.meta.actionHistory?.[item.id];
  if (!last) return true;
  const diff = (new Date(todayStr() + 'T12:00:00') - new Date(last + 'T12:00:00')) / 86400000;
  return diff >= 30;
}

function actionsAvailable(state) {
  return ACTION_POOL.filter(i => isActionAvailable(state, i));
}

function ensureTodayAction(state) {
  const t = todayStr();
  if (state.meta.actionTodayItem && state.meta.actionTodayItem.date === t) return;
  const pool = actionsAvailable(state);
  if (!pool.length) { state.meta.actionTodayItem = null; saveState(state); return; }
  const item = pool[Math.floor(Math.random() * pool.length)];
  state.meta.actionTodayItem = { date: t, id: item.id };
  saveState(state);
}

function switchActionItem(state) {
  const t = todayStr();
  const curId = state.meta.actionTodayItem?.id;
  const pool  = actionsAvailable(state).filter(i => i.id !== curId);
  if (!pool.length) return;
  const item = pool[Math.floor(Math.random() * pool.length)];
  state.meta.actionTodayItem = { date: t, id: item.id };
  saveState(state);
}

function markActionDone(state, itemId) {
  if (!state.meta.actionHistory) state.meta.actionHistory = {};
  state.meta.actionHistory[itemId] = todayStr();
  const item = ACTION_POOL.find(i => i.id === itemId);
  const ds   = todayStr();
  ensureDay(state, ds);
  state.days[ds].quests.push({
    uid: uid(), id: 'action_' + itemId,
    name: item.title, detail: item.cat,
    xp: 5, type: 'custom', done: true,
  });
  recalc(state, ds);
  state.meta.actionTodayItem = null;
  saveState(state);
}

function renderActionBlock(state) {
  const container = $('actionBlock');
  if (!container) return;

  const t    = todayStr();
  const pool = actionsAvailable(state);

  if (!pool.length) {
    container.innerHTML = `<div class="hd-done">Ты сделал всё возможное. Отдохни.</div>`;
    return;
  }

  const todayItem = state.meta.actionTodayItem;
  if (!todayItem || todayItem.date !== t) { container.innerHTML = ''; return; }

  const item = ACTION_POOL.find(i => i.id === todayItem.id);
  if (!item) { container.innerHTML = ''; return; }

  const canSwitch = pool.length > 1 || (pool.length === 1 && pool[0].id !== item.id);

  container.innerHTML = `
    <div class="hd-card">
      <div class="hd-cat">${item.cat}</div>
      <div class="hd-title">${item.title}</div>
      <div class="hd-btns">
        <button class="btn-primary hd-btn-mark" id="btnActMark">ВЫПОЛНЕНО +5 XP</button>
        <button class="btn-ghost hd-btn-next" id="btnActNext" ${canSwitch ? '' : 'disabled'}>ДРУГОЕ</button>
      </div>
    </div>`;

  $('btnActMark').addEventListener('click', () => {
    markActionDone(state, item.id);
    ensureTodayAction(state);
    renderAll(state, todayStr());
    renderActionBlock(state);
  });

  if (canSwitch) {
    $('btnActNext').addEventListener('click', () => {
      switchActionItem(state);
      renderActionBlock(state);
    });
  }
}

