function todayStr() {
  return new Date().toISOString().slice(0, 10);
}

function dateStr(d) {
  return d.toISOString().slice(0, 10);
}

function dayOfWeek(ds) {
  return new Date(ds + 'T12:00:00').getDay();
}

function isLastDayOfMonth(ds) {
  const d = new Date(ds + 'T12:00:00');
  const next = new Date(d);
  next.setDate(d.getDate() + 1);
  return next.getMonth() !== d.getMonth();
}

function dayNumber(state, ds) {
  const start   = new Date(state.meta.startDate + 'T12:00:00');
  const current = new Date(ds + 'T12:00:00');
  return Math.max(1, Math.floor((current - start) / 86400000) + 1);
}

function formatDateRu(ds) {
  return new Date(ds + 'T12:00:00').toLocaleDateString('ru-RU', {
    weekday: 'long', day: 'numeric', month: 'long'
  });
}

function yesterdayStr() {
  const d = new Date();
  d.setDate(d.getDate() - 1);
  return dateStr(d);
}

// ISO-неделя (пн-вс) в виде ключа "YYYY-Www" — нужна для недельного бонуса Воли за зал
function isoWeekKey(ds) {
  const d = new Date(ds + 'T12:00:00');
  const dayNr = (d.getDay() + 6) % 7; // 0 = понедельник
  const thursday = new Date(d);
  thursday.setDate(d.getDate() - dayNr + 3);
  const firstThursday = new Date(thursday.getFullYear(), 0, 4);
  const firstDayNr = (firstThursday.getDay() + 6) % 7;
  firstThursday.setDate(firstThursday.getDate() - firstDayNr + 3);
  const week = 1 + Math.round((thursday - firstThursday) / (7 * 86400000));
  return `${thursday.getFullYear()}-W${String(week).padStart(2, '0')}`;
}

