let _editUid = null;
let _editDs  = null;
let _state   = null;
let _editFromCalendar = false;

function openAddModal(state, ds, fromCalendar = false) {
  _editUid = null;
  _editDs  = ds;
  _state   = state;
  _editFromCalendar = fromCalendar;
  $('modalTitle').textContent     = 'НОВОЕ ЗАДАНИЕ';
  $('inputName').value            = '';
  $('inputDetail').value          = '';
  $('inputXp').value              = '5';
  $('inputSkill').value           = '';
  $('btnModalDelete').style.display = 'none';
  $('modalOverlay').classList.add('active');
  $('inputName').focus();
}

function openEditModal(state, ds, questUid, fromCalendar = false) {
  const q = state.days[ds]?.quests.find(q => q.uid === questUid);
  if (!q) return;
  _editUid = questUid;
  _editDs  = ds;
  _state   = state;
  _editFromCalendar = fromCalendar;
  $('modalTitle').textContent     = 'РЕДАКТИРОВАТЬ';
  $('inputName').value            = q.name;
  $('inputDetail').value          = q.detail || '';
  $('inputXp').value              = q.xp;
  $('inputSkill').value           = q.skill || '';
  $('btnModalDelete').style.display = 'block';
  $('modalOverlay').classList.add('active');
  $('inputName').focus();
}

function closeModal() {
  $('modalOverlay').classList.remove('active');
}

function saveModal() {
  const name = $('inputName').value.trim();
  if (!name) { $('inputName').focus(); return; }

  const xp     = Math.max(1, parseInt($('inputXp').value) || 5);
  const skill  = $('inputSkill').value || null;
  const detail = $('inputDetail').value.trim();
  const state  = _state;
  const ds     = _editDs;

  if (_editUid) {
    const q = state.days[ds]?.quests.find(q => q.uid === _editUid);
    if (q) { q.name = name; q.detail = detail; q.xp = xp; q.skill = skill; }
  } else {
    // done:true сразу — "+" это лог уже сделанного (посмотрел фильм, прочитал
    // книгу и т.п.), а не задача на потом; так оно сразу считается в XP и
    // сразу видно в истории (например в "Кругозоре"), без второго клика.
    state.days[ds].quests.push({
      uid: uid(), id: 'c_' + Date.now(),
      name, detail, xp, skill, type: 'custom', done: true,
    });
  }

  recalc(state, ds);
  saveState(state);
  closeModal();
  if (_editFromCalendar) {
    showDayDetail(ds);
    renderAll(state, todayStr());
  } else {
    renderAll(state, ds);
  }
}

function deleteModal() {
  if (!_editUid || !_editDs || !_state) return;
  const day = _state.days[_editDs];
  if (!day) return;
  day.quests = day.quests.filter(q => q.uid !== _editUid);
  recalc(_state, _editDs);
  saveState(_state);
  closeModal();
  if (_editFromCalendar) {
    showDayDetail(_editDs);
    renderAll(_state, todayStr());
  } else {
    renderAll(_state, _editDs);
  }
}

