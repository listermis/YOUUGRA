function deepClone(obj) {
  return JSON.parse(JSON.stringify(obj));
}

// Прогресс живёт в облаке (таблица youugra_state в Supabase) — не на диске,
// не в localStorage браузера, поэтому переустановка Windows на него не
// влияет. localStorage используется только как черновой кэш: если сеть
// упала на середине сохранения, работа не теряется, а при следующей загрузке
// (когда сеть есть) облако всё равно остаётся источником истины.
let _saveTimer = null;
let _saving    = false; // true пока идёт сетевой запрос сохранения
let _dirty     = false; // true если после старта запроса пришли ещё правки
let _latestState = null; // та же самая мутируемая ссылка на state всего приложения

function setSaveStatus(kind) {
  const el = document.getElementById('saveStatus');
  if (!el) return;
  const LABELS = {
    saving:  'сохранение…',
    saved:   'сохранено ✓',
    error:   'нет связи с сервером, повтор чуть позже',
    loading: 'загрузка…',
  };
  el.textContent = LABELS[kind] || '';
  el.className   = 'save-status save-status-' + kind;
}

function saveState(state) {
  try { localStorage.setItem(STORAGE_KEY, JSON.stringify(state)); } catch (_) {}
  _latestState = state;
  _dirty = true;
  setSaveStatus('saving');
  clearTimeout(_saveTimer);
  _saveTimer = setTimeout(flushSave, 1200);
}

async function flushSave() {
  if (_saving) return; // уже сохраняет — подхватит _dirty на следующем витке
  _saving = true;
  try {
    while (_dirty) {
      _dirty = false;
      try {
        await saveStateToCloud(_latestState);
        setSaveStatus('saved');
      } catch (_) {
        setSaveStatus('error');
        await new Promise(r => setTimeout(r, 2000 + Math.random() * 1500));
        _dirty = true; // повторить с самым свежим состоянием
      }
    }
  } finally {
    _saving = false;
  }
}

// сброс для разработки: youugraReset() в консоли — обнуляет прогресс и
// сразу сохраняет чистое состояние
window.youugraReset = () => {
  if (!window.confirm('Точно обнулить весь прогресс?')) return;
  const fresh = deepClone(DEFAULT_STATE);
  ensureDay(fresh, todayStr());
  recalc(fresh, todayStr());
  saveState(fresh);
  location.reload();
};

