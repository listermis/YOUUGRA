function toggleQuest(state, ds, questUid) {
  const day   = state.days[ds];
  const quest = day?.quests.find(q => q.uid === questUid);
  if (!quest) return;

  quest.done = !quest.done;

  recalc(state, ds);

  if (quest.done && ds === todayStr()) {
    updateStreakOnComplete(state);
  }

  saveState(state);
}

function recalc(state, ds) {
  const day = state.days[ds];
  if (!day) return;

  day.earnedXp = day.quests
    .filter(q => q.done)
    .reduce((s, q) => s + (q.xp || 0), 0);

  // Total XP = base + earned - штрафы
  let trackedXp = 0;
  let penaltyXpAll = 0;
  Object.values(state.days).forEach(d => {
    trackedXp += d.quests.filter(q => q.done).reduce((s, q) => s + (q.xp || 0), 0);
    const r = d.relapses || {};
    Object.entries(r).forEach(([k, cnt]) => {
      const cost = state.character.debuffs[k]?.xpCost || 0;
      penaltyXpAll += cost * cnt;
    });
  });
  state.meta.totalXp = Math.max(0, state.meta.baseXp + trackedXp - penaltyXpAll);

  // Level — порог следующего уровня растёт с каждым уровнем
  state.meta.level = computeLevelProgress(state.meta.totalXp).level;

  // Skills
  const base   = state.character.baseSkills;
  const earned = { body: 0, health: 0, psychology: 0, income: 0 };
  Object.values(state.days).forEach(d => {
    d.quests.filter(q => q.done && q.skill && earned[q.skill] !== undefined).forEach(q => {
      earned[q.skill] += q.xp || 0;
    });
  });
  Object.keys(earned).forEach(k => {
    state.character.skills[k].xp = (base[k] || 0) + earned[k];
  });

  // Стиль — считается количеством купленных вещей (квесты с навыком style), не XP
  const styleDone = Object.values(state.days)
    .flatMap(d => d.quests)
    .filter(q => q.skill === 'style' && q.done).length;
  state.character.skills.style.items = (base.style || 0) + styleDone;

  // Characteristics (stats) — считаем из квестов
  const baseStats  = state.character.baseStats;
  const statEarned = { force: 0, discipline: 0, horizons: 0, health: 0, will: 0 };
  Object.values(state.days).forEach(d => {
    d.quests.filter(q => q.done).forEach(q => {
      const key = QUEST_STAT_MAP[q.id] || (q.skill && SKILL_STAT[q.skill]);
      if (!key) return;
      const keys = Array.isArray(key) ? key : [key];
      keys.forEach(k => { if (statEarned[k] !== undefined) statEarned[k] += q.xp || 0; });
    });
  });
  Object.keys(statEarned).forEach(k => {
    if (k === 'will') return; // Воля считается ниже отдельно (нужен ещё и недельный бонус)
    state.character.stats[k] = (baseStats[k] || 0) + statEarned[k];
  });

  // Воля — по явным отметкам "чисто" (неотмеченные дни не считаются) + зал.
  // Рилсы: +1 Воля за каждый явно отмеченный чистый день.
  // Порно: +1 Воля за каждый явно отмеченный чистый день.
  // Сигареты: +1 Воля за каждый день, явно отмеченный как "в лимите" (< 4 шт).
  // Спортзал: XP квеста идёт в Волю и в Силу (statEarned.will и statEarned.force выше)
  // + отдельный бонус: +2 Воля за каждую неделю (пн-вс), где отмечено 3+ посещений.
  let willPoints = 0;
  Object.keys(state.days).sort().forEach(ds2 => {
    const tr = state.days[ds2].tracked || {};
    if (tr.reels === true) willPoints++;
    if (tr.porn  === true) willPoints++;
    if (tr.cigs  === true) willPoints++;
  });

  const gymWeekCounts = {};
  Object.entries(state.days).forEach(([ds2, d]) => {
    const gymQuest = d.quests.find(q => q.id === 'd_gym');
    if (gymQuest && gymQuest.done) {
      const wk = isoWeekKey(ds2);
      gymWeekCounts[wk] = (gymWeekCounts[wk] || 0) + 1;
    }
  });
  let gymWillBonus = 0;
  Object.values(gymWeekCounts).forEach(cnt => { if (cnt >= 3) gymWillBonus += 2; });

  state.character.stats.will = Math.max(0, (baseStats.will || 0) + willPoints + gymWillBonus + statEarned.will);

  // Virtue counter
  const questVirtues = Object.values(state.days).flatMap(d =>
    d.quests.filter(q => q.type === 'virtue' && q.done)
  ).length;
  state.meta.virtue = questVirtues + (state.meta.virtueActs?.length || 0);
}

