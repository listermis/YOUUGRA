function renderHeader(state) {
  const t      = todayStr();
  const dn     = dayNumber(state, t);
  const xp     = state.meta.totalXp;
  const lp     = computeLevelProgress(xp);
  const lvl    = lp.level;
  const toNext = lp.xpForLevel - lp.xpIntoLevel;
  const pct    = (lp.xpIntoLevel / lp.xpForLevel * 100).toFixed(1);

  $('dayNumber').textContent  = dn;
  $('streak').textContent     = state.meta.streak + ' 🔥';
  $('todayDate').textContent  = new Date(t + 'T12:00:00').toLocaleDateString('ru-RU', { day:'numeric', month:'short' });
  $('currentLevel').textContent = lvl;
  $('nextLevel').textContent    = lvl + 1;
  $('xpNumbers').textContent  = `${lp.xpIntoLevel} / ${lp.xpForLevel}`;
  $('xpToNext').textContent   = toNext;
  $('xpFill').style.width     = pct + '%';
  $('virtueNum').textContent  = state.meta.virtue;
  $('virtueModalCount').textContent = state.meta.virtue;

  // Прогноз: сколько дней до следующего уровня при текущем темпе
  const startD   = new Date(state.meta.startDate + 'T12:00:00');
  const todayD   = new Date(t + 'T12:00:00');
  const elapsed  = Math.max(1, Math.floor((todayD - startD) / 86400000) + 1);
  const avgXp    = xp / elapsed;
  const forecast = $('xpForecast');
  if (forecast) {
    if (avgXp > 0) {
      const daysLeft = Math.ceil(toNext / avgXp);
      forecast.textContent = `~${daysLeft} дн. до ур.${lvl + 1} · ${Math.round(avgXp)} XP/день`;
    } else {
      forecast.textContent = '';
    }
  }
}

