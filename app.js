const HISTORY_CONFIG = {
  horizons: {
    title:    'КРУГОЗОР',
    subtitle: 'Всё что изучил, посмотрел, прочитал',
    color:    'var(--gold)',
    filter:   q => QUEST_STAT_MAP[q.id] === 'horizons' || q.skill === 'horizons',
  },
  income: {
    title:    'ЗАРАБОТОК',
    subtitle: 'Все действия по навыку Заработок',
    color:    'var(--green)',
    filter:   q => q.skill === 'income',
  },
};

function collectHistory(state, type) {
  const conf = HISTORY_CONFIG[type];
  if (!conf) return [];
  const entries = [];
  Object.keys(state.days).sort().forEach(ds => {
    state.days[ds].quests
      .filter(q => q.done && conf.filter(q))
      .forEach(q => entries.push({ date: ds, uid: q.uid, name: q.name, detail: q.detail, xp: q.xp, rating: q.rating || null }));
  });
  return entries.reverse();
}

function setQuestRating(state, ds, questUid, rating) {
  const quest = state.days[ds]?.quests.find(q => q.uid === questUid);
  if (!quest) return;
  quest.rating = quest.rating === rating ? null : rating;
  saveState(state);
}

function renderHistoryModal(state, type) {
  const conf = HISTORY_CONFIG[type];
  if (!conf) return;
  const el = $('historyModalTitle');
  el.textContent  = conf.title;
  el.style.color  = conf.color;
  $('historyModalSubtitle').textContent = conf.subtitle;

  const entries = collectHistory(state, type);
  const listEl  = $('historyActsList');
  if (!entries.length) {
    listEl.innerHTML = '<div style="color:var(--text-dim);font-size:12px;text-align:center;padding:12px 0">Ещё нет записей</div>';
    return;
  }

  const showRating = type === 'horizons';

  listEl.innerHTML = entries.map(e => {
    const d = new Date(e.date + 'T12:00:00').toLocaleDateString('ru-RU', { day:'numeric', month:'short', year:'numeric' });
    const ratingHtml = showRating ? `
      <div class="history-rating" data-uid="${e.uid}" data-ds="${e.date}">
        <button class="rating-btn${e.rating === 'up'   ? ' r-active r-up'   : ''}" data-r="up">👍</button>
        <button class="rating-btn${e.rating === 'mid'  ? ' r-active r-mid'  : ''}" data-r="mid">👌</button>
        <button class="rating-btn${e.rating === 'down' ? ' r-active r-down' : ''}" data-r="down">👎</button>
      </div>` : '';
    return `<div class="history-entry">
      <div class="history-entry-top">
        <span class="history-entry-name">${e.name}</span>
        <span class="history-entry-xp">+${e.xp} XP</span>
      </div>
      ${e.detail ? `<div class="history-entry-detail">${e.detail}</div>` : ''}
      <div class="history-entry-footer">
        <span class="history-entry-date">${d}</span>
        ${ratingHtml}
      </div>
    </div>`;
  }).join('');

  if (showRating) {
    listEl.querySelectorAll('.history-rating').forEach(wrap => {
      wrap.querySelectorAll('.rating-btn').forEach(btn => {
        btn.addEventListener('click', () => {
          const { uid: questUid, ds } = wrap.dataset;
          setQuestRating(state, ds, questUid, btn.dataset.r);
          renderHistoryModal(state, type);
        });
      });
    });
  }
}

